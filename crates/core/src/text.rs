pub fn label(lang: Language, id: u32) -> &'static CStr { let pair = LABELS.get(id as usize).copied().unwrap_or((c"", c"")); if lang == Language::Zh { pair.1 } else { pair.0 } }
pub fn literal(lang: Language, key: Msg) -> &'static str { let p = MESSAGES[key as usize]; if lang == Language::Zh { p.1 } else { p.0 } }
pub fn en(key: Msg) -> &'static str { literal(Language::En, key) }
fn fill(pattern: &str, args: &[String]) -> String { let mut parts = pattern.split("{}"); let mut out = parts.next().unwrap_or_default().to_owned(); for (index, part) in parts.enumerate() { if let Some(arg) = args.get(index) { out.push_str(arg); } out.push_str(part); } out }
pub fn render(lang: Language, key: Msg, args: &[String]) -> String { fill(literal(lang,key),args) }
#[macro_export]
macro_rules! message { ($key:ident $(, $arg:expr)* $(,)?) => { $crate::text::render($crate::text::Language::En, $crate::text::Msg::$key, &[$(($arg).to_string()),*]) }; }
#[macro_export]
macro_rules! localized { ($lang:expr, $key:ident $(, $arg:expr)* $(,)?) => { $crate::text::render($lang, $crate::text::Msg::$key, &[$(($arg).to_string()),*]) }; }
// Canonical English messages in snapshots survive a live language switch. Match only entire known templates; values are never globally replaced.
fn captures<'a>(pattern: &str, input: &'a str) -> Option<Vec<&'a str>> { let parts: Vec<_> = pattern.split("{}").collect(); if parts.len() < 2 { return None; } let mut tail = input.strip_prefix(parts[0])?; let mut values = Vec::with_capacity(parts.len()-1); for (i, part) in parts.iter().enumerate().skip(1) { if i + 1 == parts.len() { values.push(tail.strip_suffix(*part)?); } else { let (value, next) = tail.split_once(*part)?; values.push(value); tail = next; } } Some(values) }
fn translate(input: &str, depth: u8) -> String { if depth == 0 { return input.to_owned(); } for (en, zh) in MESSAGES { if *en == input { return (*zh).to_owned(); } } for (en, zh) in MESSAGES { if let Some(values) = captures(en, input) { let raw = *en == MESSAGES[Msg::ProbeError as usize].0 || *en == MESSAGES[Msg::EncodingToolQuery as usize].0; let args: Vec<_> = values.into_iter().enumerate().map(|(i,v)| if (raw && i >= 2) || v.len() >= input.len() { v.to_owned() } else { translate(v, depth-1) }).collect(); return fill(zh, &args); } } input.to_owned() }
pub fn localize(lang: Language, input: &str) -> String { if lang == Language::En { input.to_owned() } else { translate(input, 4) } }
pub fn lines(lang: Language, input: &str) -> String { input.split('\n').map(|s| localize(lang,s)).collect::<Vec<_>>().join("\n") }
pub fn target_summary(plan: &Plan<'_>) -> String { let interlaced = matches!(plan.source.raw["field_order"].as_str(), Some("tt" | "bb" | "tb" | "bt")); message!(TargetSummary, plan.codec.label(), plan.width, plan.height, plan.source.bit_depth.map_or_else(|| en(Msg::UnknownDepth).into(), |n| message!(Depth,n)), format!("{:?}",plan.source.hdr), en(if interlaced { Msg::Bwdif } else { Msg::OriginalCadence }), format!("{:.0}",plan.video_bps as f64/1000.0), plan.audio_bps.len()) }
pub fn media_summary(info: &MediaInfo) -> String { let unknown = en(Msg::Unknown); let mut lines = vec![message!(Container, info.format.as_deref().unwrap_or(unknown), info.duration_us.map_or_else(||unknown.into(),|n|format!("{:.2} s",n as f64/1_000_000.0)))]; for s in &info.streams { let codec = s.codec.as_deref().unwrap_or(unknown); match s.kind.as_deref() { Some("video") if !s.attached_picture => { let fps=s.avg_rate.map_or_else(||en(Msg::UnknownFps).into(),|r|message!(Fps,format!("{:.3}",r.numerator as f64/r.denominator as f64))); let codec = match codec { "h264" => "H264", "hevc" => "HEVC", "av1" => "AV1", other => other }; lines.push(message!(Video, codec, s.width.map_or_else(||"?".into(),|n|n.to_string()), s.height.map_or_else(||"?".into(),|n|n.to_string()), s.bit_depth.map_or_else(||en(Msg::UnknownDepth).into(),|n|message!(Depth,n)), fps, format!("{:?}",s.hdr), s.pixel_format.as_deref().unwrap_or(en(Msg::UnknownPixel)))); lines.push(message!(Color, s.color_primaries.as_deref().unwrap_or(unknown), s.color_transfer.as_deref().unwrap_or(unknown), s.color_space.as_deref().unwrap_or(unknown), s.color_range.as_deref().unwrap_or(unknown),s.raw["field_order"].as_str().unwrap_or(unknown))); }, Some("audio") => lines.push(message!(Audio,codec,s.channels.map_or_else(||"?".into(),|n|n.to_string()),s.sample_rate.map_or_else(||"?".into(),|n|n.to_string()))), Some("subtitle")=>lines.push(message!(Subtitle,codec)), _=>{} } } lines.join("\n") }
pub fn pipeline_error(error: pipeline::Error) -> String { use pipeline::Error as E; match error { E::Budget(e)=>en(match e { budget::Error::UnknownDuration=>Msg::UnknownDuration,budget::Error::UnsupportedStreams=>Msg::UnsupportedStreams,budget::Error::UnknownGeometry=>Msg::UnknownGeometry,budget::Error::UnknownChannels=>Msg::UnknownChannels,budget::Error::InsufficientCapacity=>Msg::InsufficientCapacity,budget::Error::RateOverflow=>Msg::RateOverflow }).into(), E::Cancelled=>en(Msg::CancelDuring).into(), E::DiskFull=>en(Msg::DiskFull).into(), E::DestinationExists=>en(Msg::Exists).into(), E::InvalidDestination=>en(Msg::InvalidDestination).into(), E::SourceChanged=>en(Msg::SourceChanged).into(), E::UnsupportedDynamicHdr=>en(Msg::DynamicHdr).into(), E::UnsupportedMedia(s)=>message!(UnsupportedMedia,s), E::Io(e)=>message!(IoError,e), E::Process(s)=>s, E::NoRoute=>en(Msg::NoRoute).into(), E::HardwareRouteUnavailable=>en(Msg::HardwareUnavailable).into(), E::CapacityExceeded{limit,measured}=>message!(CapacityExceeded,measured,limit) } }
